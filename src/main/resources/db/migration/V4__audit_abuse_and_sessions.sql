CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    actor_user_id BIGINT,
    actor_username VARCHAR(128),
    target_user_id BIGINT,
    target_type VARCHAR(32),
    target_id VARCHAR(128),
    source_ip VARCHAR(64),
    user_agent VARCHAR(512)
);

CREATE INDEX idx_audit_events_occurred_at ON audit_events (occurred_at);
CREATE INDEX idx_audit_events_actor ON audit_events (actor_username);

CREATE TABLE login_attempt_buckets (
    bucket_key VARCHAR(64) PRIMARY KEY,
    window_started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    failed_attempts INTEGER NOT NULL,
    blocked_until TIMESTAMP WITH TIME ZONE
);

CREATE TABLE login_sessions (
    id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    credentials_version BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    source_ip VARCHAR(64),
    user_agent VARCHAR(512),
    CONSTRAINT fk_login_sessions_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_login_sessions_user ON login_sessions (user_id);
CREATE INDEX idx_login_sessions_expires_at ON login_sessions (expires_at);

CREATE TABLE session_refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(36) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_session_refresh_tokens_session FOREIGN KEY (session_id)
        REFERENCES login_sessions(id) ON DELETE CASCADE
);

CREATE INDEX idx_session_refresh_tokens_session ON session_refresh_tokens (session_id);

INSERT INTO permissions (name, resource, action)
VALUES ('AUDIT_READ', 'audit', 'read');

INSERT INTO role_permissions (role_id, permission_id)
SELECT roles.id, permissions.id
FROM roles CROSS JOIN permissions
WHERE roles.name = 'ADMIN' AND permissions.name = 'AUDIT_READ';
