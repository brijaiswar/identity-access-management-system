ALTER TABLE users ADD COLUMN credentials_version BIGINT NOT NULL DEFAULT 0;

CREATE TABLE account_action_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    purpose VARCHAR(32) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_account_action_tokens_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_account_action_tokens_user_purpose
    ON account_action_tokens (user_id, purpose, consumed_at);

CREATE TABLE mfa_recovery_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    code_hash VARCHAR(64) NOT NULL UNIQUE,
    used_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_mfa_recovery_codes_user FOREIGN KEY (user_id) REFERENCES users(id)
);

